% Question 9
% Product magnitude and IDFT for the board excerpts
% (speech at 43968, impulse at 55680).

N = 10;
speech = speech_ex(:);
impulse = impulse_ex(:);
nSeg = floor(length(speech) / N);

mag_acc = zeros(N, 1);
y_time = zeros(nSeg * N, 1);

for s = 0:nSeg-1
    x = speech(s*N + (1:N));
    h = impulse(s*N + (1:N));
    [Xr, Xi] = dft10(x);
    [Hr, Hi] = dft10(h);
    Yr = Xr .* Hr - Xi .* Hi;
    Yi = Xr .* Hi + Xi .* Hr;
    mag_acc = mag_acc + sqrt(Yr.^2 + Yi.^2);
    y_time(s*N + (1:N)) = idft10(Yr, Yi);
end
mag_avg = mag_acc / nSeg;
bins = 0:N-1;
t = 0:length(y_time)-1;

figure;
stem(bins, mag_avg, 'filled');
grid on;
xlabel('DFT bin k');
ylabel('|X[k] H[k]|');
title('Question 9: average 10-point product magnitude (Question 7 result)');

figure;
plot(t, y_time, 'LineWidth', 1);
grid on;
xlabel('Sample within excerpt');
ylabel('Amplitude');
title('Question 9: IDFT of X[k] H[k] (Question 8 result)');

function [rr, ii] = dft10(x)
    N = 10;
    n = (0:N-1).';
    rr = zeros(N, 1);
    ii = zeros(N, 1);
    for k = 0:N-1
        ang = -2*pi*k*n/N;
        rr(k+1) = sum(x .* cos(ang));
        ii(k+1) = sum(x .* sin(ang));
    end
end

function y = idft10(Yr, Yi)
    N = 10;
    k = (0:N-1).';
    y = zeros(N, 1);
    for n = 0:N-1
        ang = 2*pi*k*n/N;
        y(n+1) = sum(Yr .* cos(ang) - Yi .* sin(ang)) / N;
    end
end